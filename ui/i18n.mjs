export function interfaceLanguage(locale) {
  const code = String(locale || "").toLowerCase().split(/[-_]/)[0];
  return UI_LANGUAGES.includes(code) ? code : "en";
}
export class I18n {
  constructor(language = "en") { this.language = interfaceLanguage(language); }
  setLanguage(language) { this.language = interfaceLanguage(language); }
  t(message, values = {}) {
    const translation = TRANSLATIONS[message]?.[this.language] || message;
    return translation.replace(/\{(\w+)\}/g, (token, key) => key in values ? String(values[key]) : token);
  }
  apply(document) {
    document.documentElement.setAttribute("lang", this.language);
    document.documentElement.setAttribute("dir", this.language === "ar" ? "rtl" : "ltr");
    for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = this.t(node.getAttribute("data-i18n"));
    for (const attribute of ["title", "aria-label", "placeholder", "alt"]) {
      for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
        node.setAttribute(attribute, this.t(node.getAttribute(`data-i18n-${attribute}`)));
      }
    }
  }
}
